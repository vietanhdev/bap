#!/usr/bin/env bash
# Export our local changes to the upstream xiaozhi-esp32 clone as one patch file.
#
#   firmware/scripts/export_patch.sh [OUTPUT]     (default: firmware/patches/xiaozhi-esp32.patch)
#
# The patch contains `git diff` of tracked files plus untracked files (as new-file hunks),
# EXCEPT files that build.sh generates or copies in on every build:
#   main/assistant/                          <- copied from firmware/src/assistant (+ generated headers)
#   main/protocols/gemini_live_protocol.*, ticket_ssl.*  <- copied from firmware/src/protocols
#   main/boards/sensecap-watcher/config.home.json  <- generated, CONTAINS THE API KEY
#
# The vendor repository is not modified: a temporary git index is used to mark untracked files.
# The script refuses to write a patch that contains anything looking like a Google API key.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
VENDOR="$ROOT/vendor/xiaozhi-esp32"
OUT="${1:-$ROOT/firmware/patches/xiaozhi-esp32.patch}"
PINNED_COMMIT="${XIAOZHI_COMMIT:-aaf1eb7798cabee87a0c6a0649aabf4d17e9e383}"

EXCLUDES=(
    ':(exclude)main/assistant'
    ':(exclude)main/protocols/gemini_live_protocol.cc'
    ':(exclude)main/protocols/gemini_live_protocol.h'
    ':(exclude)main/protocols/ticket_ssl.cc'
    ':(exclude)main/protocols/ticket_ssl.h'
    ':(exclude)main/boards/sensecap-watcher/config.home.json'
)

[[ -d "$VENDOR/.git" ]] || { echo "error: $VENDOR is not a git clone" >&2; exit 1; }

head_commit="$(git -C "$VENDOR" rev-parse HEAD)"
if [[ "$head_commit" != "$PINNED_COMMIT" ]]; then
    echo "warning: vendor HEAD is $head_commit, expected pinned $PINNED_COMMIT" >&2
    echo "         update PINNED_COMMIT in apply_patch.sh/export_patch.sh if this is intended" >&2
fi

tmp_index="$(mktemp)"
tmp_patch="$(mktemp)"
trap 'rm -f "$tmp_index" "$tmp_patch"' EXIT

# Copy the real index so `git add -N` (intent-to-add) does not touch vendor/.git/index.
cp "$VENDOR/.git/index" "$tmp_index"
export GIT_INDEX_FILE="$tmp_index"

mapfile -t untracked < <(git -C "$VENDOR" ls-files --others --exclude-standard -- . "${EXCLUDES[@]}")
if ((${#untracked[@]})); then
    git -C "$VENDOR" add --intent-to-add -- "${untracked[@]}"
fi

{
    echo "# Local changes to github.com/78/xiaozhi-esp32 at $PINNED_COMMIT"
    echo "# Generated by firmware/scripts/export_patch.sh; apply with firmware/scripts/apply_patch.sh"
    git -C "$VENDOR" diff --binary --no-color --no-ext-diff HEAD -- . "${EXCLUDES[@]}"
} > "$tmp_patch"
unset GIT_INDEX_FILE

if grep -qE 'AIza[0-9A-Za-z_-]{20,}' "$tmp_patch"; then
    echo "error: the patch contains a Google API key (AIza...). Refusing to write it." >&2
    grep -nE 'AIza[0-9A-Za-z_-]{20,}' "$tmp_patch" | sed -E 's/AIza[0-9A-Za-z_-]+/AIza<REDACTED>/g' >&2
    exit 1
fi

mkdir -p "$(dirname "$OUT")"
cp "$tmp_patch" "$OUT"
files="$(grep -c '^diff --git ' "$OUT" || true)"
echo "Wrote $OUT ($files files, $(wc -l < "$OUT") lines)"
